function main() {
  const generated = generate();
  const outPath = resolve(ROOT, OUT);
  if (process.argv.includes("--check")) {
    const existing = readFileSync(outPath, "utf8");
    if (normalizeLineEndings(existing) !== normalizeLineEndings(generated)) {
      console.error(`${OUT} is stale. Run: npm run contract:generate`);
      process.exit(1);
    }
    return;
  }
  writeFileSync(outPath, generated, "utf8");
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n/g, "\n");
}

function generate() {
  const parsed = new Map();
  const sourceText = SOURCES.map((source) => readSource(source)).join("\n");
  const hash = createHash("sha256").update(sourceText).digest("hex").slice(0, 16);
  for (const source of SOURCES) {
    for (const item of parseRustFile(source, readSource(source))) {
      if (INCLUDE.has(item.name) && !parsed.has(item.name)) {
        parsed.set(item.name, item);
      }
    }
  }

  const missing = [...INCLUDE].filter((name) => !parsed.has(name));
  if (missing.length > 0) {
    throw new Error(`Missing contract items: ${missing.join(", ")}`);
  }

  const chunks = [
    "// Generated by scripts/generate-bus-contract.mjs.",
    "// Do not edit by hand; run `npm run contract:generate`.",
    `export const GENERATED_BUS_CONTRACT_HASH = "${hash}";`,
    "",
  ];
  for (const name of INCLUDE) {
    const item = parsed.get(name);
    chunks.push(renderItem(item), "");
  }
  chunks.push(
    "export interface GeneratedBusContractTypeMap {",
    ...[...INCLUDE].map((name) => `  ${name}: ${name};`),
    "}",
  );
  return `${chunks.join("\n").trimEnd()}\n`;
}

function readSource(source) {
  return normalizeLineEndings(readFileSync(resolve(ROOT, source), "utf8"));
}

function parseRustFile(source, text) {
  const items = [];
  const lines = text.split(/\r?\n/);
  let attrs = [];
  for (let i = 0; i < lines.length; i += 1) {
    const trimmed = lines[i].trim();
    if (trimmed.startsWith("#[cfg(test)]") && lines[i + 1]?.trim().startsWith("mod tests")) {
      break;
    }
    if (trimmed.startsWith("#[") || trimmed.startsWith("///")) {
      attrs.push(trimmed);
      continue;
    }
    const structMatch = trimmed.match(/^pub struct (\w+)\s*\{/);
    if (structMatch) {
      const name = structMatch[1];
      const fields = [];
      i += 1;
      let fieldAttrs = [];
      for (; i < lines.length; i += 1) {
        const fieldLine = lines[i].trim();
        if (fieldLine.startsWith("#[") || fieldLine.startsWith("///")) {
          fieldAttrs.push(fieldLine);
          continue;
        }
        if (fieldLine === "}") break;
        const fieldMatch = fieldLine.match(/^pub\s+(\w+):\s+(.+),$/);
        if (fieldMatch) {
          fields.push({
            name: fieldMatch[1],
            rustType: fieldMatch[2],
            attrs: fieldAttrs,
          });
        }
        fieldAttrs = [];
      }
      items.push({ kind: "struct", name, attrs, fields, source });
      attrs = [];
      continue;
    }

    const enumMatch = trimmed.match(/^pub enum (\w+)\s*\{/);
    if (enumMatch) {
      const name = enumMatch[1];
      const variants = [];
      i += 1;
      for (; i < lines.length; i += 1) {
        const variantLine = lines[i].trim();
        if (variantLine.startsWith("///") || variantLine.startsWith("#[")) continue;
        if (variantLine === "}") break;
        const variantMatch = variantLine.match(/^(\w+),$/);
        if (variantMatch) variants.push(variantMatch[1]);
      }
      items.push({ kind: "enum", name, attrs, variants, source });
      attrs = [];
      continue;
    }
    if (trimmed !== "") attrs = [];
  }
  return items;
}

function renderItem(item) {
  if (item.kind === "enum") {
    const renameAll = serdeRenameAll(item.attrs);
    const values = item.variants.map((variant) => `"${renameVariant(variant, renameAll)}"`);
    const singleLine = `export type ${item.name} = ${values.join(" | ")};`;
    if (singleLine.length <= 100) {
      return singleLine;
    }
    return (
      [`export type ${item.name} =`, ...values.map((value) => `  | ${value}`)].join("\n") + ";"
    );
  }

  const lines = [`export interface ${item.name} {`];
  for (const field of item.fields) {
    const optional = field.attrs.some((attr) => attr.includes("skip_serializing_if"));
    lines.push(`  ${field.name}${optional ? "?" : ""}: ${tsType(field.rustType)};`);
  }
  lines.push("}");
  return lines.join("\n");
}

function serdeRenameAll(attrs) {
  const attr = attrs.find((line) => line.includes("rename_all"));
  return attr?.match(/rename_all\s*=\s*"([^"]+)"/)?.[1] ?? null;
}

function renameVariant(variant, renameAll) {
  if (renameAll === "lowercase") return variant.toLowerCase();
  if (renameAll === "snake_case") {
    return variant
      .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
      .replace(/([A-Z])([A-Z][a-z])/g, "$1_$2")
      .toLowerCase();
  }
  return variant;
}

function tsType(raw) {
  const type = raw.trim();
  const option = genericInner(type, "Option");
  if (option) return `${tsType(option)} | null`;
  const vec = genericInner(type, "Vec");
  if (vec) return `${tsType(vec)}[]`;
  if (type === "String" || type === "PathBuf") return "string";
  if (type === "bool") return "boolean";
  if (/^(u|i)(8|16|32|64|size)$/.test(type)) return "number";
  return type;
}

function genericInner(type, name) {
  const prefix = `${name}<`;
  if (!type.startsWith(prefix) || !type.endsWith(">")) return null;
  return type.slice(prefix.length, -1).trim();
}

